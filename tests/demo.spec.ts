import { test, expect } from "@playwright/test";
test("네 탭의 금액과 모바일 너비, 설정 이동을 확인한다", async ({ page }, testInfo) => {
  await page.goto("/dashboard");
  await expect(page.getByTestId("expected-gap")).toHaveText("500,000원");
  for (const [label, heading, path] of [["홈", "우리의 새로운 시작을", "dashboard"], ["할 일", "우리집 체크리스트", "tasks"], ["지출", "지출관리", "expenses"], ["자금", "자금계획", "funding"]]) {
    await page.getByRole("navigation").getByRole("link", { name: label, exact: true }).click();
    await expect(page.getByRole("heading", { level: 1 })).toContainText(heading);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await page.screenshot({ path: testInfo.outputPath(`${path}.png`), fullPage: true });
  }
  await page.getByRole("link", { name: "설정", exact: true }).click();
  await page.getByLabel("입주할 날짜").fill("2026-12-25");
  await page.getByRole("button", { name: "날짜 저장" }).click();
  await expect(page.getByRole("status")).toContainText("변경했어요");
  await page.getByRole("navigation").getByRole("link", { name: "홈", exact: true }).click();
  await expect(page.getByText("2026. 12. 25 입주 예정")).toBeVisible();
});
test("할 일을 작성·수정·완료·삭제하고 빈 상태를 확인한다", async ({ page }) => {
  await page.goto("/tasks?new=1");
  await page.getByRole("button", { name: "저장", exact: true }).click();
  await expect(page.getByRole("alert")).toContainText("1~100자");
  await page.getByLabel("할 일 이름 (필수)").fill("테스트 할 일");
  await page.getByRole("button", { name: "저장", exact: true }).click();
  await expect(page.getByRole("heading", { name: "테스트 할 일", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "테스트 할 일 수정" }).click();
  await page.getByLabel("할 일 이름 (필수)").fill("수정한 할 일");
  await page.getByRole("button", { name: "저장", exact: true }).click();
  await page.getByRole("checkbox", { name: "수정한 할 일 완료" }).check();
  await page.getByRole("button", { name: "완료", exact: true }).click();
  await expect(page.getByRole("heading", { name: "수정한 할 일" })).toBeVisible();
  await page.getByRole("button", { name: "수정한 할 일 삭제" }).click();
  await page.getByRole("button", { name: "취소", exact: true }).click();
  await expect(page.getByRole("heading", { name: "수정한 할 일" })).toBeVisible();
  await page.getByRole("button", { name: "수정한 할 일 삭제" }).click();
  await page.getByRole("button", { name: "삭제 확인" }).click();
  await expect(page.getByRole("heading", { name: "수정한 할 일" })).toHaveCount(0);
  await page.getByLabel("카테고리 필터").selectOption("기타");
  await expect(page.getByText("조건에 맞는 할 일이 없어요.")).toBeVisible();
});
test("지출 입력 오류와 확정 0원, 탭 간 반영 및 초기화를 확인한다", async ({ page }) => {
  await page.goto("/expenses?new=1");
  await page.getByLabel("지출 이름 (필수)").fill("테스트 지출");
  await page.getByLabel("예상금액 (원)").fill("-1.5");
  await page.getByRole("button", { name: "저장", exact: true }).click();
  await expect(page.getByRole("alert")).toContainText("정수");
  await page.getByLabel("예상금액 (원)").fill("100000");
  await page.getByRole("button", { name: "저장", exact: true }).click();
  await page.getByRole("navigation").getByRole("link", { name: "홈", exact: true }).click();
  await expect(page.getByTestId("expected-gap")).toHaveText("600,000원");
  await page.getByRole("navigation").getByRole("link", { name: "지출", exact: true }).click();
  await page.getByRole("button", { name: "테스트 지출 수정" }).click();
  await page.getByLabel("확정금액 (원)").fill("0");
  await page.getByRole("button", { name: "저장", exact: true }).click();
  await page.getByRole("navigation").getByRole("link", { name: "홈", exact: true }).click();
  await expect(page.getByTestId("expected-gap")).toHaveText("500,000원");
  await page.reload();
  await page.getByRole("navigation").getByRole("link", { name: "지출", exact: true }).click();
  await expect(page.getByRole("heading", { name: "테스트 지출" })).toHaveCount(0);
});
test("자금 추가·수정·삭제와 키보드로 시트 닫기를 확인한다", async ({ page }) => {
  await page.goto("/funding");
  await page.getByRole("button", { name: "자금 추가" }).click();
  await page.keyboard.press("Escape");
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await page.getByRole("button", { name: "자금 추가" }).click();
  await page.getByLabel("자금 이름 (필수)").fill("추가 저축");
  await page.getByLabel("금액 (원, 필수)").fill("500000");
  await page.getByLabel("상태", { exact: true }).selectOption("confirmed");
  await page.getByRole("button", { name: "저장", exact: true }).click();
  await page.getByRole("navigation").getByRole("link", { name: "홈", exact: true }).click();
  await expect(page.getByTestId("expected-gap")).toHaveText("0원");
  await page.getByRole("navigation").getByRole("link", { name: "자금", exact: true }).click();
  await page.getByRole("button", { name: "추가 저축 수정" }).click();
  await page.getByLabel("금액 (원, 필수)").fill("600000");
  await page.getByRole("button", { name: "저장", exact: true }).click();
  await expect(page.getByText("600,000원", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "추가 저축 삭제" }).click();
  await page.getByRole("button", { name: "삭제 확인" }).click();
  await expect(page.getByRole("heading", { name: "추가 저축" })).toHaveCount(0);
});

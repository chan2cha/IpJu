import { test, expect } from "@playwright/test";
test("상품 후보를 비교·선택·수정·삭제하며 지출액은 유지한다", async ({ page }, testInfo) => {
  await page.goto("/expenses");
  const comparison = page.getByRole("region", { name: "가전 구매 상품·업체 비교", exact: true });
  await expect(comparison.getByText("비교할 상품이나 업체를 추가해 보세요.", { exact: false })).toBeVisible();
  async function add(name: string, vendor: string, amount: string) {
    await comparison.getByRole("button", { name: "후보 추가" }).click();
    await page.getByLabel("상품·서비스명 (필수)").fill(name);
    await page.getByLabel("업체명 (필수)").fill(vendor);
    await page.getByLabel("총 견적금액 (원)").fill(amount);
    await page.getByLabel("모델명·서비스 구성").fill("설치 포함");
    await page.getByLabel("상품·업체 사이트 주소").fill("https://example.com/product?id=1");
    await page.getByLabel("비교 메모").fill("배송일 확인 필요");
    await page.getByRole("button", { name: "저장", exact: true }).click();
  }
  await add("냉장고 A", "가전 업체 A", "1000000");
  await add("냉장고 B", "가전 업체 B", "1200000");
  await expect(comparison.getByText("+200,000원", { exact: true })).toBeVisible();
  await expect(comparison.getByRole("link", { name: "냉장고 A 사이트 열기 (새 탭)" })).toHaveAttribute("href", "https://example.com/product?id=1");
  await expect(comparison.getByRole("link", { name: "냉장고 A 사이트 열기 (새 탭)" })).toHaveAttribute("rel", "noopener noreferrer");
  await comparison.getByRole("button", { name: "냉장고 B 선택", exact: true }).click();
  await expect(comparison.getByRole("status")).toContainText("냉장고 B · 가전 업체 B");
  await page.getByRole("button", { name: "가전 구매 수정", exact: true }).click();
  await page.getByRole("button", { name: "저장", exact: true }).click();
  await expect(comparison.getByRole("status")).toContainText("냉장고 B");
  await comparison.getByRole("button", { name: "냉장고 B 후보 수정" }).click();
  await page.getByLabel("총 견적금액 (원)").fill("900000");
  await page.getByRole("button", { name: "저장", exact: true }).click();
  await comparison.getByRole("button", { name: "낮은 견적순 보기" }).click();
  expect(await comparison.getByRole("region", { name: "가전 구매 후보 비교표" }).evaluate(element => element.scrollLeft)).toBe(0);
  await expect(comparison.getByRole("columnheader").nth(1)).toContainText("냉장고 B");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("comparison.png"), fullPage: true });
  await page.getByRole("navigation").getByRole("link", { name: "홈", exact: true }).click();
  await expect(page.getByTestId("expected-gap")).toHaveText("500,000원");
  await page.getByRole("navigation").getByRole("link", { name: "지출", exact: true }).click();
  await comparison.getByRole("button", { name: "냉장고 B 후보 삭제" }).click();
  await page.getByRole("button", { name: "취소", exact: true }).click();
  await expect(comparison.getByRole("status")).toContainText("냉장고 B");
  await comparison.getByRole("button", { name: "냉장고 B 후보 삭제" }).click();
  await page.getByRole("button", { name: "삭제 확인" }).click();
  await expect(comparison.getByRole("status")).toContainText("아직 선택한 후보가 없어요");
  await expect(comparison.getByRole("columnheader", { name: "냉장고 B", exact: true })).toHaveCount(0);
});
test("후보 필수값·금액·주소 오류와 미정/0원을 처리한다", async ({ page }) => {
  await page.goto("/expenses");
  const comparison = page.getByRole("region", { name: "입주 청소 상품·업체 비교", exact: true });
  await comparison.getByRole("button", { name: "후보 추가" }).click();
  await page.getByRole("button", { name: "저장", exact: true }).click();
  await expect(page.getByRole("alert")).toContainText("상품·서비스명");
  await page.getByLabel("상품·서비스명 (필수)").fill("청소 서비스");
  await page.getByRole("button", { name: "저장", exact: true }).click();
  await expect(page.getByRole("alert")).toContainText("업체명");
  await page.getByLabel("업체명 (필수)").fill("청소 업체");
  await page.getByLabel("총 견적금액 (원)").fill("-1.5");
  await page.getByRole("button", { name: "저장", exact: true }).click();
  await expect(page.getByRole("alert")).toContainText("정수");
  await page.getByLabel("총 견적금액 (원)").fill("");
  await page.getByLabel("상품·업체 사이트 주소").fill("javascript:alert(1)");
  await page.getByRole("button", { name: "저장", exact: true }).click();
  await expect(page.getByRole("alert")).toContainText("http");
  await page.getByLabel("상품·업체 사이트 주소").fill("");
  await page.getByRole("button", { name: "저장", exact: true }).click();
  await expect(comparison.getByText("비교 불가", { exact: true })).toBeVisible();
  await expect(comparison.getByText("최저 견적", { exact: true })).toHaveCount(0);
  await comparison.getByRole("button", { name: "청소 서비스 후보 수정" }).click();
  await page.getByLabel("총 견적금액 (원)").fill("0");
  await page.getByRole("button", { name: "저장", exact: true }).click();
  await expect(comparison.getByText("0원", { exact: true })).toBeVisible();
});
